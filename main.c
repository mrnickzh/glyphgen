GLuint fontTexture;

static void error_callback(int error, const char* description) {
    fprintf(stderr, "error: %s\n", description);
}

static void key_callback(GLFWwindow* window, int key, int scancode, int action, int mods) {
    if (key == GLFW_KEY_ESCAPE && action == GLFW_PRESS)
        glfwSetWindowShouldClose(window, GLFW_TRUE);
}

GLuint load_font_texture(const char* filename) {
    int width, height, channels;
    unsigned char* data = stbi_load(filename, &width, &height, &channels, 0);
    if (!data) {
        fprintf(stderr, "failed to load font atlas image: %s\n", filename);
        return 0;
    }

    GLuint texture;
    glGenTextures(1, &texture);
    glBindTexture(GL_TEXTURE_2D, texture);

    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP);

    glTexImage2D(GL_TEXTURE_2D, 0, GL_ALPHA, width, height, 0, GL_ALPHA, GL_UNSIGNED_BYTE, data);

    stbi_image_free(data);
    return texture;
}

void draw_char(char c, float* cursor_x, float* cursor_y) {
    glyph_data glyph = gg_get_char_data(font_array, c, cursor_x, cursor_y);

    if (glyph.x1 > glyph.x0 && glyph.y1 > glyph.y0) {
        glBegin(GL_QUADS);
            glTexCoord2f(glyph.uvx0, glyph.uvy0); glVertex2f(glyph.x0, glyph.y0);
            glTexCoord2f(glyph.uvx1, glyph.uvy0); glVertex2f(glyph.x1, glyph.y0);
            glTexCoord2f(glyph.uvx1, glyph.uvy1); glVertex2f(glyph.x1, glyph.y1);
            glTexCoord2f(glyph.uvx0, glyph.uvy1); glVertex2f(glyph.x0, glyph.y1);
        glEnd();
    }
}

void draw_text(const char* text, float x, float y) {
    float cursor_x = x;
    float cursor_y = y;
    size_t len = strlen(text);
    
    for (size_t i = 0; i < len; i++) {
		draw_char(text[i], &cursor_x, &cursor_y);
	}
}

int main(void) {
    glfwSetErrorCallback(error_callback);

    if (!glfwInit()) {
        fprintf(stderr, "failed to initialize GLFW\n");
        exit(EXIT_FAILURE);
    }

    glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 1);
    glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 2);

    GLFWwindow* window = glfwCreateWindow(640, 480, "glyphgen example", NULL, NULL);
    if (!window) {
        fprintf(stderr, "failed to create GLFW window\n");
        glfwTerminate();
        exit(EXIT_FAILURE);
    }

    glfwSetKeyCallback(window, key_callback);
    glfwMakeContextCurrent(window);
    glfwSwapInterval(1); 

    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    fontTexture = load_font_texture("montserrat_glyphs.png");
    if (fontTexture == 0) {
        glfwDestroyWindow(window);
        glfwTerminate();
        exit(EXIT_FAILURE);
    }

    while (!glfwWindowShouldClose(window)) {
        int width, height;
        glfwGetFramebufferSize(window, &width, &height);
        glViewport(0, 0, width, height);

        glClearColor(0.1f, 0.1f, 0.15f, 1.0f);
        glClear(GL_COLOR_BUFFER_BIT);

        glMatrixMode(GL_PROJECTION);
        glLoadIdentity();
        glOrtho(0, width, height, 0, -1, 1); 
        glMatrixMode(GL_MODELVIEW);
        glLoadIdentity();

        glEnable(GL_TEXTURE_2D);
        glBindTexture(GL_TEXTURE_2D, fontTexture);
        glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
        
        glColor3f(1.0f, 1.0f, 1.0f); 

        draw_text("TESTING ___ ABC 123...", 30.0f, 50.0f);
		
		draw_text("SECOND LINE !!!", 30.0f, 100.0f);

        glfwSwapBuffers(window);
        glfwPollEvents();
    }

    glDeleteTextures(1, &fontTexture);
    glfwDestroyWindow(window);
    glfwTerminate();
    
    exit(EXIT_SUCCESS);
}
